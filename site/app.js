const root = document.documentElement;
const languageButton = document.querySelector("[data-lang-toggle]");
const themeButton = document.querySelector("[data-theme-toggle]");
const description = document.querySelector('meta[name="description"]');
const colorPreference = window.matchMedia("(prefers-color-scheme: dark)");
const requestedLanguage = new URLSearchParams(window.location.search).get("lang")?.toLowerCase();
const linkedLanguage = requestedLanguage === "en"
  ? "en"
  : requestedLanguage === "zh" || requestedLanguage === "zh-cn"
    ? "zh"
    : null;

let language = linkedLanguage || localStorage.getItem("site-language") || (navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en");

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  root.lang = language === "zh" ? "zh-CN" : "en";
  document.title = copy[language].title;
  description.setAttribute("content", copy[language].description);

  document.querySelectorAll("[data-copy]").forEach((element) => {
    const key = element.dataset.copy;
    if (copy[language][key]) {
      element.textContent = copy[language][key];
    }
  });

  document.querySelectorAll("[data-src-en][data-src-zh]").forEach((image) => {
    const source = language === "zh" ? image.dataset.srcZh : image.dataset.srcEn;
    const alt = language === "zh" ? image.dataset.altZh : image.dataset.altEn;
    if (image.getAttribute("src") !== source) {
      image.setAttribute("src", source);
    }
    if (alt) {
      image.setAttribute("alt", alt);
    }
  });

  languageButton.textContent = language === "zh" ? "EN" : "中文";
  languageButton.setAttribute("aria-label", language === "zh" ? "Switch to English" : "切换到中文");
  localStorage.setItem("site-language", language);
  const url = new URL(window.location.href);
  url.searchParams.set("lang", language === "zh" ? "zh-CN" : "en");
  window.history.replaceState({}, "", url);
  updateThemeLabel();
}

function currentTheme() {
  const savedTheme = root.dataset.theme;
  if (savedTheme === "light" || savedTheme === "dark") {
    return savedTheme;
  }
  return colorPreference.matches ? "dark" : "light";
}

function updateThemeLabel() {
  const nextTheme = currentTheme() === "dark" ? "light" : "dark";
  const labels = language === "zh"
    ? { light: "浅色", dark: "深色" }
    : { light: "Light", dark: "Dark" };
  themeButton.textContent = labels[nextTheme];
  themeButton.setAttribute("aria-label", language === "zh" ? `切换到${labels[nextTheme]}模式` : `Switch to ${labels[nextTheme].toLowerCase()} mode`);
}

const savedTheme = localStorage.getItem("site-theme");
if (savedTheme === "light" || savedTheme === "dark") {
  root.dataset.theme = savedTheme;
}

themeButton.addEventListener("click", () => {
  const nextTheme = currentTheme() === "dark" ? "light" : "dark";
  root.dataset.theme = nextTheme;
  localStorage.setItem("site-theme", nextTheme);
  updateThemeLabel();
});

languageButton.addEventListener("click", () => {
  applyLanguage(language === "zh" ? "en" : "zh");
});

colorPreference.addEventListener("change", updateThemeLabel);

applyLanguage(language);
